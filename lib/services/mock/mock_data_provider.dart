  static List<EnergyUsageModel> getEnergyUsage() {
    final now = DateTime.now();
    
    final dailyData = List.generate(30, (index) {
      final date = now.subtract(Duration(days: 29 - index));
      return EnergyDataPoint(
        date: date,
        usage: 80.0 + (index % 10) * 10.0 + (date.weekday == DateTime.sunday ? 30.0 : 0.0),
        estimatedSaved: 15.0 + (index % 5) * 5.0,
      );
    });

    final weeklyData = List.generate(12, (index) {
      final date = now.subtract(Duration(days: (11 - index) * 7));
      return EnergyDataPoint(
        date: date,
        usage: 500.0 + (index % 4) * 50.0,
        estimatedSaved: 100.0 + (index % 3) * 20.0,
      );
    });

    final monthlyData = List.generate(12, (index) {
      final date = DateTime(now.year, now.month - (11 - index), 1);
      return EnergyDataPoint(
        date: date,
        usage: 2000.0 + (index % 5) * 200.0,
        estimatedSaved: 400.0 + (index % 4) * 50.0,
      );
    });

    return [
      EnergyUsageModel(
        id: 'ENG-DAILY',
        zoneId: 'ALL',
        period: EnergyPeriod.daily,
        dataPoints: dailyData,
        totalUsage: dailyData.fold(0.0, (sum, dp) => sum + dp.usage),
        totalEstimatedSaved: dailyData.fold(0.0, (sum, dp) => sum + (dp.estimatedSaved ?? 0)),
        averageUsage: dailyData.map((dp) => dp.usage).reduce((a, b) => a + b) / dailyData.length,
      ),
      EnergyUsageModel(
        id: 'ENG-WEEKLY',
        zoneId: 'ALL',
        period: EnergyPeriod.weekly,
        dataPoints: weeklyData,
        totalUsage: weeklyData.fold(0.0, (sum, dp) => sum + dp.usage),
        totalEstimatedSaved: weeklyData.fold(0.0, (sum, dp) => sum + (dp.estimatedSaved ?? 0)),
        averageUsage: weeklyData.map((dp) => dp.usage).reduce((a, b) => a + b) / weeklyData.length,
      ),
      EnergyUsageModel(
        id: 'ENG-MONTHLY',
        zoneId: 'ALL',
        period: EnergyPeriod.monthly,
        dataPoints: monthlyData,
        totalUsage: monthlyData.fold(0.0, (sum, dp) => sum + dp.usage),
        totalEstimatedSaved: monthlyData.fold(0.0, (sum, dp) => sum + (dp.estimatedSaved ?? 0)),
        averageUsage: monthlyData.map((dp) => dp.usage).reduce((a, b) => a + b) / monthlyData.length,
      ),
    ];
  }
